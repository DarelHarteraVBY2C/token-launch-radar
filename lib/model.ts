// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown with the market's own values, never mixed
// into the ranked board.
//
// Implied value is what a protocol's token would be worth if it launched today, estimated from the
// market's own prices. For every category, the benchmark is the median market-cap-to-TVL ratio of the
// snapshot's protocols in that category that already trade; a category with fewer than three
// comparables falls back to the global median, so no thin category invents its own multiple. Then:
//
//   benchmark  = category median mcap/TVL of launched comparables (global median when thin)
//   growth     = clamp(change_7d, -30, 30) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.8 + min(age_days, 1095) / 1095 x 0.2   (age_days unknown: 365)
//   breadth    = 1 + 0.01 x min(chains - 1, 10)
//   implied    = max(1, round(tvl_usd x benchmark x growthMult x maturity x breadth))
//
// The constants are the model's, stated in the dashboard and changeable in one place. No protocol
// name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
  min_comparables: number;
  comparable_floor_usd: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -30,
  growth_cap: 30,
  maturity_floor: 0.8,
  maturity_range: 0.2,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.01,
  breadth_max_chains: 10,
  min_comparables: 3,
  comparable_floor_usd: 50_000_000,
};

